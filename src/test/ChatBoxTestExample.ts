/**
 * 聊天框自检消息。
 *
 * ## 现在验的是什么
 *
 * 保留模型换成「消息不消失、按 tag 各留 50 条、只画最后几条、可滚回去看」之后，
 * 这个自检要能一眼看出：
 *
 * 1. **消息不再自己消失** —— 灌完等半分钟，屏幕上的行应该原样还在
 * 2. **一屏几条不再是定数** —— 面板 320 高，让出顶部筛选条 34 px 后消息区 286 高。
 *    **每条的高度按内容算**（折几行就占几个 20 像素，上限 5 行），
 *    所以「系统提示 #1」这种一行的小消息只占 20 像素，一屏能摞十几条；
 *    「战斗日志 #2」那种要折 5 行的就占 100。**这正是这一轮要看的效果** ——
 *    短消息不再白占一整格
 * 3. **每条开头有 `[时:分:秒]`** —— 时间戳是 `Console.say()` 入队那一刻打的
 * 4. **四个频道都混着有** —— 筛选条按频道过滤，数据得先铺开才验得了
 * 5. **长消息折到第五行，第 5 行末尾有 `…`** —— 战斗 #1 和 #2 是两根探针：
 *    - **#1 是「五行以内装得下」**：它从「战斗日志」一直排到句末，不该大片留白
 *    - **#2 是「超过五行」**：它一定得在**第五行**末尾以 **`…`** 收尾。看不见省略号
 *      说明折行没起作用，内容是被 frame 硬生生裁掉的（那种截断是无声的）
 *
 * ✅ **看不到的那些不是丢了** —— 滚轮（鼠标停在面板上）或拖右侧滑块就能翻回去，
 * 拖到顶能一直看到本条注释开头说的第 1 条。
 *
 * 数据量刻意大过一屏，就是为了让把手**出现**（`maxOffset > 0`）。
 * 轨道本身现在常显（不够一屏时把手会铺满整条），所以这里不再是非灌满不可。
 *
 * ## 队列节流
 *
 * `Console.init` 里那个定时器是**每 0.1 秒只放行一条**的，所以
 * `SEED_COUNT` 条要 `SEED_COUNT × 0.1` 秒才铺完 —— 20 条是 2 秒。
 * 想快速验证**上限**（某一类灌到 50 条以上）别去加这个常量，那要等 5 秒以上；
 * 直接把 `Console.init` 里那个 `0.1` 改小更快，改完记得改回来。
 *
 * ⚠️ 这是演示数据，不是正式内容。验证完把 `main.ts` 里那一行调用删掉即可。
 */

import { ChatBoxUI } from "src/system/ui/ChatBoxUI";
import { Console } from "src/system/console";
import { createLogger } from "src/utils/logger";

const log = createLogger("ChatBoxDemo");

/** 每个频道灌几条。20 条总量刻意大于一屏能放的条数，好看出「窗口只画最新的」+ 让把手出现 */
const SEED_PER_CHANNEL = 5;

/**
 * 四个频道各灌 `SEED_PER_CHANNEL` 条，交替出手，方便一眼看出窗口里混着几类。
 *
 * 战斗 #1 / #2 故意写长 —— 它们是「折行」的两根探针，判读方法见文件头第 5 条。
 *
 * ⚠️ 这两条在**默认的「全部」视图里看不清** —— 那个视图画的是最新的十来条，
 * 而消息是按 `系统→战斗→警告→玩家` 的次序灌的，先灌的被挤到屏幕外了。
 * **点一下筛选条的「战斗」**才看得舒服：战斗类一共 5 条，按内容算高度是
 * `3 行 + 5 行 + 1 行 + 1 行 + 1 行 = 11 行`（220 像素）+ 4 个间距 = 240，
 * **一屏 286 装得下，不用滚** —— 两根探针能同时看到，对比着读。
 */
export function seedChatBoxDemo(): void {
  for (let i = 1; i <= SEED_PER_CHANNEL; i++) {
    ChatBoxUI.system(`系统提示 #${i}：这条应为黄色`);
    ChatBoxUI.combat(
      i === 1
        ? "战斗日志 #1：这条是「五行以内装得下」的探针，它应该从「战斗日志」一路排到句末，行尾只留一点点空白，不该大片留白"
        : i === 2
          ? "战斗日志 #2：这条是「超过五行」的探针，它必须在第五行的末尾以省略号收尾；如果末尾没有省略号，说明折行没生效、内容是被引擎硬生生裁掉的，而且裁掉的地方不会有任何提示，玩家只会看到一句没说完的话"
          : `战斗日志 #${i}：这条应为灰色`
    );
    ChatBoxUI.warn(`警告 #${i}：这条应为红色`);
    Console.say(`玩家消息 #${i}：这条应为白色（走 Console.say 直发）`, "FFFFFF", "PLAYER");
  }

  log.info(
    `聊天框演示消息已入队 ${SEED_PER_CHANNEL * 4} 条，当前队列长度=${Console.getQueueLength()}`
  );
}
